"""Tabulate the issue-hour distribution of the archived canonical forecasts.

Protocol section 3.2.2 (docs/EVALUATION_PROTOCOL.md) requires the issue-hour
distribution table to be generated by a repository script into results/ - not
prose, not hand-written. This is **sample metadata only**: issue times, UTC
bands and counts. It computes no skill metric (no CRPS, Brier or reliability).

    uv run --project backend python scripts/issue_hour_distribution.py \
        --archive-dir path/to/forecasts

Inputs are the canonical archive parquets
``forecasts/<issue_date>/openmeteo-ensemble_<issue_date>.parquet`` (first
archive of an issue date, frozen). They are never committed to git; fetch them
from the public Hugging Face dataset first, e.g.::

    uv run --project backend --with huggingface_hub python -c "
    from huggingface_hub import hf_hub_download
    hf_hub_download('Akunimal/prisma-climate',
        'forecasts/2026-11-11/openmeteo-ensemble_2026-11-11.parquet',
        repo_type='dataset', local_dir='.')"

The issue time is read from the parquet's ``issue_time`` column, never from
the file name or the wall clock. Every value in results/ comes only from this
script.

Outputs under results/archive_issue_hours/:
- issue_hours.csv - one row per issue date (issue_time, hour, band, rows, file)
- issue_hours.md  - the table plus counts per UTC band
"""

from __future__ import annotations

import argparse
import sys
from datetime import UTC, datetime
from pathlib import Path

import pandas as pd

REPO = Path(__file__).resolve().parents[1]
DEFAULT_ARCHIVE_DIR = REPO / "forecasts"
DEFAULT_OUT_DIR = REPO / "results" / "archive_issue_hours"
FILE_GLOB = "**/openmeteo-ensemble_*.parquet"
BAND_MORNING = "00:00-11:59"
BAND_AFTERNOON = "12:00-23:59"


def band_for_hour(hour: int) -> str:
    """UTC stratum of an issue hour, per protocol 3.2.2."""
    if not 0 <= hour <= 23:
        raise ValueError(f"hour out of range: {hour}")
    return BAND_MORNING if hour < 12 else BAND_AFTERNOON


def load_issue_stamp(path: Path) -> tuple[pd.Timestamp, int]:
    """Single UTC issue timestamp of one archive parquet, plus its row count."""
    frame = pd.read_parquet(path)
    if "issue_time" not in frame.columns:
        raise ValueError(f"{path.name}: missing issue_time column")
    stamps = pd.to_datetime(frame["issue_time"], utc=True, errors="raise")
    if stamps.isna().any():
        raise ValueError(f"{path.name}: issue_time contains nulls")
    distinct = sorted(set(stamps))
    if len(distinct) != 1:
        raise ValueError(
            f"{path.name}: expected a single issue_time, found {len(distinct)}"
        )
    return distinct[0], len(frame)


def collect(archive_dir: Path) -> list[dict[str, object]]:
    """One metadata row per archive parquet under archive_dir."""
    if not archive_dir.is_dir():
        raise FileNotFoundError(f"archive dir not found: {archive_dir}")
    paths = sorted(archive_dir.glob(FILE_GLOB))
    if not paths:
        raise FileNotFoundError(f"no {FILE_GLOB} under {archive_dir}")

    rows: list[dict[str, object]] = []
    for path in paths:
        stamp, n_rows = load_issue_stamp(path)
        rows.append(
            {
                "issue_date": stamp.strftime("%Y-%m-%d"),
                "issue_time_utc": stamp.strftime("%Y-%m-%d %H:%M:%S"),
                "hour_utc": stamp.hour,
                "band": band_for_hour(stamp.hour),
                "rows": n_rows,
                "file": path.relative_to(archive_dir).as_posix(),
            }
        )

    rows.sort(key=lambda row: str(row["issue_time_utc"]))
    dates = [str(row["issue_date"]) for row in rows]
    if len(dates) != len(set(dates)):
        raise ValueError("two archive files share one issue date")
    return rows


def render_markdown(rows: list[dict[str, object]]) -> str:
    now = datetime.now(UTC).strftime("%Y-%m-%d %H:%M:%S UTC")
    morning = sum(1 for row in rows if row["band"] == BAND_MORNING)
    afternoon = sum(1 for row in rows if row["band"] == BAND_AFTERNOON)

    lines: list[str] = []
    lines.append("# Archive issue-hour distribution")
    lines.append("")
    lines.append(
        f"Generated {now} by `scripts/issue_hour_distribution.py` "
        "from the canonical archive parquets (file paths are relative to the "
        "archive root)."
    )
    lines.append(
        "Values in `results/` come only from this script. "
        "**Sample metadata only** - no CRPS, Brier or reliability is computed here."
    )
    lines.append(
        "Bands are the UTC strata of protocol section 3.2.2 "
        "(`docs/EVALUATION_PROTOCOL.md`)."
    )
    lines.append("")
    lines.append("## Per issue date")
    lines.append("")
    lines.append("| issue_date | issue_time (UTC) | hour | band | rows | file |")
    lines.append("|---|---|---|---|---:|---|")
    for row in rows:
        lines.append(
            f"| {row['issue_date']} | {row['issue_time_utc']} | "
            f"{row['hour_utc']:02d} | {row['band']} | {row['rows']} | "
            f"`{row['file']}` |"
        )
    lines.append("")
    lines.append("## Counts per band")
    lines.append("")
    lines.append("| band | issue dates |")
    lines.append("|---|---:|")
    lines.append(f"| {BAND_MORNING} | {morning} |")
    lines.append(f"| {BAND_AFTERNOON} | {afternoon} |")
    lines.append(f"| **total** | **{len(rows)}** |")
    lines.append("")
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--archive-dir",
        type=Path,
        default=DEFAULT_ARCHIVE_DIR,
        help="directory holding the canonical forecasts/<date>/*.parquet files",
    )
    parser.add_argument(
        "--out-dir",
        type=Path,
        default=DEFAULT_OUT_DIR,
        help="directory for issue_hours.csv and issue_hours.md",
    )
    args = parser.parse_args(argv)

    try:
        rows = collect(args.archive_dir)
    except FileNotFoundError as exc:
        print(exc, file=sys.stderr)
        return 1

    args.out_dir.mkdir(parents=True, exist_ok=True)
    csv_path = args.out_dir / "issue_hours.csv"
    fieldnames = [
        "issue_date",
        "issue_time_utc",
        "hour_utc",
        "band",
        "rows",
        "file",
    ]
    with csv_path.open("w", encoding="utf-8", newline="") as handle:
        frame = pd.DataFrame(rows, columns=fieldnames)
        frame.to_csv(handle, index=False)

    md_path = args.out_dir / "issue_hours.md"
    md_path.write_text(render_markdown(rows), encoding="utf-8")

    morning = sum(1 for row in rows if row["band"] == BAND_MORNING)
    afternoon = len(rows) - morning
    print(f"wrote {csv_path}")
    print(f"wrote {md_path}")
    print(
        f"summary: {len(rows)} issue dates, "
        f"{morning} in {BAND_MORNING}, {afternoon} in {BAND_AFTERNOON}"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
