"""Data-freshness audit and stale-station check (results/qc/).

Run: ``python -m prisma.qc``

Writes script outputs only (never hand-edited):

- ``results/qc/source_freshness.csv`` — last ok observation per
  source x location x variable (t2m_max, t2m_min, precip).
- ``results/qc/station_staleness.csv`` — QC stale-station check
  (``station_status``, > 30 days, GHCN-Daily).
- ``results/qc/day_coverage.csv`` — ok-day counts per source x location x
  variable, the evidence behind the t2m_min vs t2m_max paired-day difference.
- ``results/qc/freshness.md`` — human summary.
"""

from __future__ import annotations

import argparse
from pathlib import Path

import pandas as pd

from ..ingest.base import find_repo_root, utc_now
from .rules import STALE_DAYS, source_freshness, station_status

DAILY_VARS = ("t2m_max", "t2m_min", "precip")


def load_frame(path: Path) -> pd.DataFrame:
    frame = pd.read_parquet(path)
    frame["time"] = pd.to_datetime(frame["time"])
    return frame


def day_coverage(frame: pd.DataFrame) -> pd.DataFrame:
    """Ok-day counts per source x location x variable for the daily variables."""
    ok = frame.loc[
        frame["quality_flag"].eq("ok") & frame["variable"].isin(DAILY_VARS)
    ]
    counts = (
        ok.groupby(["source", "location", "variable"])["time"]
        .nunique()
        .rename("ok_days")
        .reset_index()
    )
    return counts


def non_ok_counts(frame: pd.DataFrame) -> pd.DataFrame:
    """Distinct days flagged suspect/fail per source x variable (QC effect)."""
    flagged = frame.loc[
        frame["quality_flag"].ne("ok") & frame["variable"].isin(DAILY_VARS)
    ]
    counts = (
        flagged.groupby(["source", "variable", "quality_flag"])["time"]
        .nunique()
        .rename("flagged_days")
        .reset_index()
    )
    return counts


def _md_table(frame: pd.DataFrame) -> str:
    headers = [str(column) for column in frame.columns]
    lines = [
        "| " + " | ".join(headers) + " |",
        "| " + " | ".join("---" for _ in headers) + " |",
    ]
    for row in frame.itertuples(index=False, name=None):
        cells = ["" if pd.isna(value) else str(value) for value in row]
        lines.append("| " + " | ".join(cells) + " |")
    return "\n".join(lines)


def render_freshness_md(
    freshness: pd.DataFrame,
    staleness: pd.DataFrame,
    coverage: pd.DataFrame,
    flagged: pd.DataFrame,
    *,
    as_of: pd.Timestamp,
    store_refresh: dict[str, pd.Timestamp],
) -> str:
    """Human summary computed from the audit tables (never hand-edited)."""
    per_source = (
        freshness.groupby(["source", "variable"])
        .agg(
            last_observation=("last_observation", "max"),
            locations=("location", "nunique"),
        )
        .reset_index()
        .sort_values(["source", "variable"])
    )
    per_source["days_since"] = (as_of.normalize() - per_source["last_observation"]).dt.days

    ghcn_last = freshness.loc[freshness["source"].eq("ghcn-daily"), "last_observation"].max()
    era5_last = freshness.loc[freshness["source"].eq("openmeteo-era5"), "last_observation"].max()

    lines = [
        "# Source freshness audit",
        "",
        f"Generated by `python -m prisma.qc` on {as_of} (UTC). "
        f"Stale threshold: > {STALE_DAYS} days.",
        "",
        "## Last ok observation per source x variable",
        "",
        _md_table(per_source),
        "",
        "Store refresh (`retrieved_at` max): "
        + "; ".join(
            f"{source} {refresh}" for source, refresh in sorted(store_refresh.items())
        ),
        "",
        "## ghcn-daily last ok date per station",
        "",
    ]

    ghcn = freshness.loc[freshness["source"].eq("ghcn-daily")]
    pivot = ghcn.pivot_table(
        index="location", columns="variable", values="last_observation", aggfunc="max"
    )
    for variable in DAILY_VARS:
        if variable not in pivot.columns:
            pivot[variable] = pd.NaT
    pivot = pivot[list(DAILY_VARS)].reset_index()
    lines += [_md_table(pivot), ""]

    lines += [
        f"## Stale-station check (ghcn-daily, > {STALE_DAYS} days)",
        "",
    ]
    if staleness.empty:
        lines.append("_No GHCN observations available._")
    else:
        stale_n = int(staleness["stale"].sum())
        lines.append(
            f"{stale_n} of {len(staleness)} stations stale as of "
            f"{as_of.date()} (full table: `results/qc/station_staleness.csv`)."
        )
        if stale_n:
            oldest = staleness.sort_values("days_since", ascending=False).iloc[0]
            lines.append(
                f"Oldest: {oldest['location']} — last ok observation "
                f"{pd.Timestamp(oldest['last_observation']).date()} "
                f"({int(oldest['days_since'])} days)."
            )
    lines += ["", "## t2m_min vs t2m_max ok-day coverage", ""]

    totals = (
        coverage.groupby(["source", "variable"])["ok_days"].sum().unstack(fill_value=0)
    )
    for variable in DAILY_VARS:
        if variable not in totals.columns:
            totals[variable] = 0
    totals["min_minus_max"] = totals["t2m_min"] - totals["t2m_max"]
    totals["pct_more_min"] = (
        100.0 * totals["min_minus_max"] / totals["t2m_max"].replace(0, pd.NA)
    ).astype(float).round(1)
    coverage_table = totals.reset_index()
    lines += [_md_table(coverage_table), ""]

    for source, row in totals.iterrows():
        tmax = int(row["t2m_max"])
        tmin = int(row["t2m_min"])
        if tmax == tmin:
            lines.append(
                f"- {source}: t2m_max and t2m_min cover the same {tmax} ok days "
                "(no coverage asymmetry)."
            )
        else:
            extra = tmin - tmax
            share = 100.0 * extra / tmax if tmax else 0.0
            lines.append(
                f"- {source}: t2m_min has {extra} more ok days than t2m_max "
                f"({share:.1f}% more) — a coverage gap in the stored source rows, "
                "not a QC artefact (flagged days below are negligible)."
            )
    if not flagged.empty:
        lines += [
            "",
            "Days flagged by QC (suspect/fail) per source x variable:",
            "",
            _md_table(flagged),
        ]

    lines += [
        "",
        "## Implication",
        "",
        f"- The cross-source comparison period can only reach {ghcn_last.date()} "
        f"(ghcn-daily), while {era5_last.date()} is available from ERA5: the "
        "overlap ends at the GHCN end date.",
        "- GHCN-Daily being stale means recent-forecast verification in Phase 1 "
        "depends on the SMN Argentina connector until GHCN refreshes.",
        "",
    ]
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    root = find_repo_root()
    parser = argparse.ArgumentParser(prog="python -m prisma.qc")
    parser.add_argument(
        "--era5",
        type=Path,
        default=root / "data" / "raw" / "openmeteo-era5.parquet",
        help="path to the normalized ERA5 Parquet",
    )
    parser.add_argument(
        "--ghcn",
        type=Path,
        default=root / "data" / "raw" / "ghcn-daily.parquet",
        help="path to the normalized GHCN-Daily Parquet",
    )
    parser.add_argument(
        "--out-dir",
        type=Path,
        default=root / "results" / "qc",
        help="directory for the freshness audit outputs",
    )
    args = parser.parse_args(argv)

    era5 = load_frame(args.era5)
    ghcn = load_frame(args.ghcn)
    combined = pd.concat([era5, ghcn], ignore_index=True)

    as_of = utc_now()
    freshness = source_freshness(combined, as_of=as_of)
    staleness = station_status(combined, as_of=as_of)
    coverage = day_coverage(combined)
    flagged = non_ok_counts(combined)

    store_refresh: dict[str, pd.Timestamp] = {}
    for frame in (era5, ghcn):
        if "retrieved_at" in frame.columns and not frame["retrieved_at"].empty:
            source = str(frame["source"].iloc[0])
            refresh = pd.to_datetime(frame["retrieved_at"]).max()
            store_refresh[source] = refresh.tz_localize(None) if refresh.tzinfo else refresh

    args.out_dir.mkdir(parents=True, exist_ok=True)
    freshness.to_csv(args.out_dir / "source_freshness.csv", index=False)
    staleness.to_csv(args.out_dir / "station_staleness.csv", index=False)
    coverage.to_csv(args.out_dir / "day_coverage.csv", index=False)
    (args.out_dir / "freshness.md").write_text(
        render_freshness_md(
            freshness,
            staleness,
            coverage,
            flagged,
            as_of=as_of,
            store_refresh=store_refresh,
        ),
        encoding="utf-8",
    )
    stale_n = int(staleness["stale"].sum()) if not staleness.empty else 0
    print(f"freshness rows -> {(args.out_dir / 'source_freshness.csv').relative_to(root)}")
    print(f"stale stations: {stale_n} of {len(staleness)} (>{STALE_DAYS} days)")
    print(f"summary -> {(args.out_dir / 'freshness.md').relative_to(root)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
